// API reference content. Source of truth: the route schemas in apps/server (also served as OpenAPI 3.1 at
// GET /v1/openapi.json) and docs/API.md. Example ids, addresses and hashes are illustrative.
import { BASE } from './snippets';

export type HttpMethod = 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE';
export interface Field { name: string; type: string; req?: boolean; desc: string }
export interface Endpoint {
  id: string;
  method: HttpMethod;
  path: string;
  title: string;
  auth: string;
  desc: string[];
  pathParams?: Field[];
  query?: Field[];
  body?: Field[];
  returns: string;
  node?: string;
  curl: string;
  status: string;
  response: string;
  notes?: string[];
}
export interface Resource {
  id: string;
  title: string;
  intro: string[];
  object?: { name: string; fields: Field[]; json: string };
  endpoints: Endpoint[];
}

const j = (v: unknown) => JSON.stringify(v, null, 2);

function curl(method: HttpMethod, path: string, o: { body?: unknown; idem?: string; query?: string } = {}): string {
  const url = `${BASE}${path}${o.query ? `?${o.query}` : ''}`;
  const lines = [o.query ? `curl "${url}"` : `curl ${url}`];
  if (method !== 'GET' && method !== 'POST') lines.push(`  -X ${method}`);
  else if (method === 'POST' && o.body === undefined) lines.push('  -X POST');
  lines.push('  -H "Authorization: Bearer sk_test_..."');
  if (o.idem) lines.push(`  -H "Idempotency-Key: ${o.idem}"`);
  if (o.body !== undefined) {
    lines.push('  -H "Content-Type: application/json"');
    const body = j(o.body).split('\n').map((l, i) => (i === 0 ? l : `  ${l}`)).join('\n');
    lines.push(`  -d '${body}'`);
  }
  return lines.join(' \\\n');
}

